library IEEE;
use IEEE.STD_LOGIC_1164.ALL;
use IEEE.NUMERIC_STD.ALL;
use IEEE.STD_LOGIC_TEXTIO.ALL;
use STD.TEXTIO.ALL;

entity uart_testbench is
end uart_testbench;

architecture Behavioral of uart_testbench is

    -- ????????? ?????????
    constant CLK_PERIOD : time    := 20 ns;                            -- 50 ???
    constant CLK_FREQ   : integer := 50_000_000;
    constant BAUD_RATE  : integer := 115200;                           -- ????????? ????????
    constant BIT_PERIOD : time    := 1_000_000_000 ns / BAUD_RATE;     -- ?????? ?????? ????

    -- ??????????? ??????? (UUT - Unit Under Test)
    component uart_tx
        generic (CLK_FREQ : integer := 50_000_000; BAUD_RATE : integer := 115200);
        port (
            clk      : in  STD_LOGIC;
            reset    : in  STD_LOGIC;
            tx_start : in  STD_LOGIC;
            tx_data  : in  STD_LOGIC_VECTOR(7 downto 0);
            tx       : out STD_LOGIC;
            tx_busy  : out STD_LOGIC
        );
    end component;

    component uart_rx
        generic (CLK_FREQ : integer := 50_000_000; BAUD_RATE : integer := 115200);
        port (
            clk      : in  STD_LOGIC;
            reset    : in  STD_LOGIC;
            rx       : in  STD_LOGIC;
            rx_data  : out STD_LOGIC_VECTOR(7 downto 0);
            rx_ready : out STD_LOGIC;
            rx_error : out STD_LOGIC
        );
    end component;

    -- ??????? ?????????
    signal clk       : STD_LOGIC := '0';
    signal reset     : STD_LOGIC := '1';
    signal tx_start  : STD_LOGIC := '0';
    signal tx_data   : STD_LOGIC_VECTOR(7 downto 0) := (others => '0');
    signal tx_line   : STD_LOGIC;
    signal tx_busy   : STD_LOGIC;
    signal rx_line   : STD_LOGIC := '1';
    signal rx_data   : STD_LOGIC_VECTOR(7 downto 0);
    signal rx_ready  : STD_LOGIC;
    signal rx_error  : STD_LOGIC;
    signal sim_done  : boolean := false;

    -- ??????? ???????????? std_logic_vector ? hex-????? (??? ???????? ??????)
    function to_hex_str(slv : std_logic_vector(7 downto 0)) return string is
        variable result : string(1 to 2);
    begin
        for i in 0 to 1 loop
            case slv(7 - i*4 downto 4 - i*4) is
                when "0000" => result(i+1) := '0';
                when "0001" => result(i+1) := '1';
                when "0010" => result(i+1) := '2';
                when "0011" => result(i+1) := '3';
                when "0100" => result(i+1) := '4';
                when "0101" => result(i+1) := '5';
                when "0110" => result(i+1) := '6';
                when "0111" => result(i+1) := '7';
                when "1000" => result(i+1) := '8';
                when "1001" => result(i+1) := '9';
                when "1010" => result(i+1) := 'A';
                when "1011" => result(i+1) := 'B';
                when "1100" => result(i+1) := 'C';
                when "1101" => result(i+1) := 'D';
                when "1110" => result(i+1) := 'E';
                when "1111" => result(i+1) := 'F';
                when others => result(i+1) := 'X';
            end case;
        end loop;
        return result;
    end function;

begin

    -- ????????? ????????? ??????? 50 ???
    clk_gen : process
    begin
        while not sim_done loop
            clk <= '0', '1' after CLK_PERIOD/2;
            wait for CLK_PERIOD;
        end loop;
        wait;
    end process;

    -- ??????????? ??????????
    U_TX : uart_tx
        generic map (CLK_FREQ => CLK_FREQ, BAUD_RATE => BAUD_RATE)
        port map (
            clk => clk, reset => reset, tx_start => tx_start,
            tx_data => tx_data, tx => tx_line, tx_busy => tx_busy
        );

    -- ??????????? ????????
    U_RX : uart_rx
        generic map (CLK_FREQ => CLK_FREQ, BAUD_RATE => BAUD_RATE)
        port map (
            clk => clk, reset => reset, rx => rx_line,
            rx_data => rx_data, rx_ready => rx_ready, rx_error => rx_error
        );

    -- Loopback: Tx ? Rx (??? ?????????????)
    rx_line <= tx_line;

    --------------------------------------------------------------------
    -- ???????? ?????? ??????????
    --------------------------------------------------------------------
    stimulus : process

        -- ????????? ???????? ?????? ?????
        procedure send_byte(data : std_logic_vector(7 downto 0)) is
        begin
            wait until tx_busy = '0';           -- ???????, ???? ????????? ???????
            wait until rising_edge(clk);
            tx_data  <= data;
            tx_start <= '1';
            report "? Sending: 0x" & to_hex_str(data);
            wait until rising_edge(clk);
            tx_start <= '0';
            wait until tx_busy = '1';           -- ?????????????, ?? ???????? ????????
            wait until tx_busy = '0';           -- ??????? ?????????? ????????
        end procedure;

        -- ????????? ????????? ????????? ?????
        procedure check_byte(expected : std_logic_vector(7 downto 0)) is
        begin
            wait until rx_ready = '1' for 500 us;
            if rx_ready = '1' then
                if rx_data = expected and rx_error = '0' then
                    report "? PASS: Received 0x" & to_hex_str(rx_data) severity note;
                else
                    report "? FAIL: Expected 0x" & to_hex_str(expected) &
                           ", got 0x" & to_hex_str(rx_data) &
                           ", rx_error = " & std_logic'image(rx_error) severity error;
                end if;
            else
                report "? TIMEOUT: No data received!" severity error;
            end if;
        end procedure;

    begin
        report "=== ??????? ?????????? UART (115200 ???) ===";

        -- ???????? ???????
        reset <= '1';
        wait for 100 ns;
        reset <= '0';
        wait for 500 ns;

        report "--- ???? 1: ?????????? ????? ---";
        send_byte(x"55"); check_byte(x"55");  -- 01010101
        send_byte(x"AA"); check_byte(x"AA");  -- 10101010

        report "--- ???? 2: ???????? ???????? ---";
        send_byte(x"00"); check_byte(x"00");
        send_byte(x"FF"); check_byte(x"FF");

        report "--- ???? 3: ????????? ????? ---";
        send_byte(x"12"); check_byte(x"12");
        send_byte(x"A5"); check_byte(x"A5");
        send_byte(x"5A"); check_byte(x"5A");

        report "--- ???? 4: ASCII-????? 'UART' ---";
        send_byte(x"55"); check_byte(x"55");  -- U
        send_byte(x"41"); check_byte(x"41");  -- A
        send_byte(x"52"); check_byte(x"52");  -- R
        send_byte(x"54"); check_byte(x"54");  -- T

        wait for 2 us;

        report "=== ??? ????? ???????? ???????! UART ?????? ???????? ===";
        sim_done <= true;
        wait;
    end process;

    -- ?????????? ??????? (????????? ????????????)
    monitor : process
    begin
        wait until rx_ready = '1';
        report "???????: ???????? ???? 0x" & to_hex_str(rx_data);
    end process;

end Behavioral;