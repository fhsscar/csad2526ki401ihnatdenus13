library IEEE;
use IEEE.STD_LOGIC_1164.ALL;
use IEEE.NUMERIC_STD.ALL;

entity uart_rx is
    generic (
        CLK_FREQ  : integer := 50_000_000;  -- ??????? ??????? ????? (??)
        BAUD_RATE : integer := 115200       -- ????????? ???????? (???)
    );
    port (
        clk       : in  STD_LOGIC;
        reset     : in  STD_LOGIC;
        rx        : in  STD_LOGIC;
        rx_data   : out STD_LOGIC_VECTOR(7 downto 0);
        rx_ready  : out STD_LOGIC;
        rx_error  : out STD_LOGIC
    );
end uart_rx;

architecture Behavioral of uart_rx is

    -- ????????? ??? 16-???????? ???????????????????
    constant OVERSAMPLE : integer := 16;
    constant BAUD_DIV   : integer := CLK_FREQ / (BAUD_RATE * OVERSAMPLE);

    -- ????? ??????????? ???????? (FSM)
    type state_type is (IDLE, START_BIT, DATA_BITS, STOP_BIT);
    signal state : state_type := IDLE;

    -- ??????????
    signal baud_counter   : integer range 0 to BAUD_DIV-1   := 0;  -- ????????? ??????
    signal sample_counter : integer range 0 to OVERSAMPLE-1 := 0;  -- ????????? ???????
    signal bit_counter    : integer range 0 to 7            := 0;  -- ????????? ????? ?????

    -- ???????? ?????
    signal rx_data_reg    : STD_LOGIC_VECTOR(7 downto 0) := (others => '0');
    signal tick           : STD_LOGIC := '0';  -- ??????? ???? ??? ?? 16 ??????
    signal rx_sync        : STD_LOGIC_VECTOR(1 downto 0) := "11"; -- ????????????? ?????

begin

    -- ??????? ????
    rx_data <= rx_data_reg;

    -- === 1. ????????????? ???????? ??????? (?????? ??? ????????????????) ===
    sync_process : process(clk, reset)
    begin
        if reset = '1' then
            rx_sync <= "11";
        elsif rising_edge(clk) then
            rx_sync <= rx_sync(0) & rx;     -- ??? ??????? ?????????????
        end if;
    end process;

    -- === 2. ????????? ????????? ???????? (16× ??? baud rate) ===
    baud_gen : process(clk, reset)
    begin
        if reset = '1' then
            baud_counter <= 0;
            tick         <= '0';
        elsif rising_edge(clk) then
            tick <= '0';
            if baud_counter = BAUD_DIV - 1 then
                baud_counter <= 0;
                tick         <= '1';        -- ??????? ????? 16 ??????
            else
                baud_counter <= baud_counter + 1;
            end if;
        end if;
    end process;

    -- === 3. ???????? ?????????? ??????? (FSM) ???????? ===
    fsm : process(clk, reset)
    begin
        if reset = '1' then
            state         <= IDLE;
            rx_ready      <= '0';
            rx_error      <= '0';
            rx_data_reg   <= (others => '0');
            bit_counter   <= 0;
            sample_counter <= 0;

        elsif rising_edge(clk) then
            rx_ready <= '0';
            rx_error <= '0';

            if tick = '1' then
                case state is

                    -- ?????????? ?????-????
                    when IDLE =>
                        sample_counter <= 0;
                        if rx_sync(1) = '0' then
                            state <= START_BIT;
                        end if;

                    -- ????????? ?????-???? ?? ?????? (8-? ????? ? 16)
                    when START_BIT =>
                        if sample_counter = OVERSAMPLE/2 - 1 then
                            if rx_sync(1) = '0' then
                                state <= DATA_BITS;
                            else
                                state <= IDLE;      -- ?????? ?????
                            end if;
                            sample_counter <= 0;
                        else
                            sample_counter <= sample_counter + 1;
                        end if;

                    -- ?????? 8 ????? ????? (?? ?????? ??????? ????)
                    when DATA_BITS =>
                        if sample_counter = OVERSAMPLE - 1 then
                            rx_data_reg(bit_counter) <= rx_sync(1);
                            sample_counter <= 0;
                            if bit_counter = 7 then
                                state <= STOP_BIT;
                            else
                                bit_counter <= bit_counter + 1;
                            end if;
                        else
                            sample_counter <= sample_counter + 1;
                        end if;

                    -- ????????? ????-????
                    when STOP_BIT =>
                        if sample_counter = OVERSAMPLE - 1 then
                            if rx_sync(1) = '1' then
                                rx_ready <= '1';            -- ???? ??????
                            else
                                rx_error <= '1';            -- ??????? ??????
                            end if;
                            state <= IDLE;
                        else
                            sample_counter <= sample_counter + 1;
                        end if;
                end case;
            end if;
        end if;
    end process;

end Behavioral;