library IEEE;
use IEEE.STD_LOGIC_1164.ALL;
use IEEE.NUMERIC_STD.ALL;

entity uart_tx is
    Generic (
        CLK_FREQ    : integer := 50_000_000;  -- ??????? ?????????? ????? (50 ???)
        BAUD_RATE   : integer := 9600         -- ??????? ????????? (9600 bps)
    );
    Port (
        clk         : in  STD_LOGIC;          -- ????????? ???????? ??????
        reset       : in  STD_LOGIC;          -- ?????? ????????
        tx_start    : in  STD_LOGIC;          -- ??????? ????????
        tx_data     : in  STD_LOGIC_VECTOR(7 downto 0);  -- ???? ??? ????????
        tx          : out STD_LOGIC;          -- ??????? ????? UART
        tx_busy     : out STD_LOGIC           -- ????????? ??????????
    );
end uart_tx;

architecture Behavioral of uart_tx is
    
    -- ????????? ??? ?????????? ???????? ???????? ???????
    constant BAUD_DIV : integer := CLK_FREQ / BAUD_RATE;
    
    -- ????? ????????? ????????
    type state_type is (IDLE, START_BIT, DATA_BITS, STOP_BIT);
    signal state : state_type := IDLE;
    
    -- ????????? ????????
    signal baud_counter : integer range 0 to BAUD_DIV-1 := 0;  -- ????????? ??? ????????? ???????? ?????????
    signal bit_counter  : integer range 0 to 7 := 0;            -- ????????? ??? ????? (0-7)
    signal tx_data_reg  : STD_LOGIC_VECTOR(7 downto 0) := (others => '0');  -- ??????? ?????????? ?????
    signal tx_reg       : STD_LOGIC := '1';                     -- ??????? ?????? TX (idle = '1')
    signal tick         : STD_LOGIC := '0';                     -- ?????? ?????????? ???????? ?????????
    
begin
    
    -- ??????? ???????
    tx <= tx_reg;
    tx_busy <= '0' when state = IDLE else '1';
    
    -- ?????? ????????? ???????? ????????? ???????? ?????????
    baud_rate_generator: process(clk, reset)
    begin
        if reset = '1' then
            baud_counter <= 0;
            tick <= '0';
        elsif rising_edge(clk) then
            tick <= '0';  -- ?? ????????????? tick = 0
            
            if state = IDLE then
                baud_counter <= 0;  -- ???????? ?????????? ? ????? IDLE
            else
                if baud_counter = BAUD_DIV-1 then
                    baud_counter <= 0;
                    tick <= '1';  -- ????????? tick ????? ?????? ???????? ?????????
                else
                    baud_counter <= baud_counter + 1;
                end if;
            end if;
        end if;
    end process;
    
    -- ???????? ?????? ????????? ???????? UART ??????????
    uart_tx_fsm: process(clk, reset)
    begin
        if reset = '1' then
            state <= IDLE;
            tx_reg <= '1';  -- ????? TX ? ????? ?????? = '1'
            bit_counter <= 0;
            tx_data_reg <= (others => '0');
            
        elsif rising_edge(clk) then
            case state is
                
                -- ???? ??????????: ??????? ??????? tx_start
                when IDLE =>
                    tx_reg <= '1';  -- ????? ? ???????? ????? (idle)
                    bit_counter <= 0;
                    
                    if tx_start = '1' then
                        tx_data_reg <= tx_data;  -- ?????????? ???? ??? ????????
                        state <= START_BIT;
                    end if;
                
                -- ???? ???????? ?????????? ???? (0)
                when START_BIT =>
                    tx_reg <= '0';  -- ????????? ??? ?????? '0'
                    
                    if tick = '1' then
                        state <= DATA_BITS;
                        bit_counter <= 0;
                    end if;
                
                -- ???? ???????? 8 ??? ????? (LSBFirst)
                when DATA_BITS =>
                    tx_reg <= tx_data_reg(bit_counter);  -- ????????? ??? ?? ?????
                    
                    if tick = '1' then
                        if bit_counter = 7 then
                            state <= STOP_BIT;
                        else
                            bit_counter <= bit_counter + 1;
                        end if;
                    end if;
                
                -- ???? ???????? ????????? ???? (1)
                when STOP_BIT =>
                    tx_reg <= '1';  -- ???????? ??? ?????? '1'
                    
                    if tick = '1' then
                        state <= IDLE;  -- ???????????? ? ???? ??????????
                    end if;
                    
            end case;
        end if;
    end process;
    
end Behavioral;